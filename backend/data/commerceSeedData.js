function buildSeatLayout(rows = 6) {
  const seats = [];
  const cols = ["A", "B", "C", "D"];
  for (let r = 1; r <= rows; r += 1) {
    cols.forEach((c) => {
      seats.push({
        seatNumber: `${r}${c}`,
        deck: "lower",
        type: r <= 2 ? "sleeper" : "seater",
        priceModifier: r <= 2 ? 150 : 0,
      });
    });
  }
  return { rows, cols: 4, seats };
}

